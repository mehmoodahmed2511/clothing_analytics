-- "November's orders arrive." Run after your first `dbt build`,
-- then run `dbt build --select fct_order_items+` and watch it MERGE only the new rows.
-- Safe to run twice: it skips orders that are already there.
USE ROLE TRANSFORMER;
USE WAREHOUSE TRANSFORM_WH;

INSERT INTO CLOTHING_RAW.STORE.ORDERS
  SELECT * FROM CLOTHING_RAW.INCOMING.ORDERS
  WHERE ORDER_ID NOT IN (SELECT ORDER_ID FROM CLOTHING_RAW.STORE.ORDERS);

INSERT INTO CLOTHING_RAW.STORE.ORDER_ITEMS
  SELECT * FROM CLOTHING_RAW.INCOMING.ORDER_ITEMS
  WHERE ORDER_ITEM_ID NOT IN (SELECT ORDER_ITEM_ID FROM CLOTHING_RAW.STORE.ORDER_ITEMS);
